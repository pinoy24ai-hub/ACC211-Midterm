/* ACC 211 General Ledger Practice: PDF certificate of completion (jsPDF + AutoTable, bundled in /vendor). */
(function () {
  'use strict';

  const E = window.GLEngine;
  const BRAND = [31, 78, 121];
  const GOLD = [200, 134, 42];
  const INK = [27, 37, 51];
  const MUTED = [107, 119, 137];

  // Standard PDF fonts only cover Latin-1, so swap typographic characters for plain ones.
  function t(s) {
    return String(s == null ? '' : s)
      .replace(/[‘’]/g, "'").replace(/[“”]/g, '"')
      .replace(/[–—−]/g, '-').replace(/[^\x00-\xFF]/g, '?');
  }

  function download(state, statement, certId) {
    const jsPDF = window.jspdf.jsPDF;
    const doc = new jsPDF({ unit: 'pt', format: 'letter' });
    const W = doc.internal.pageSize.getWidth();
    const H = doc.internal.pageSize.getHeight();
    const cx = W / 2;

    // ---- Border ----
    doc.setDrawColor.apply(doc, BRAND).setLineWidth(3).rect(24, 24, W - 48, H - 48);
    doc.setDrawColor.apply(doc, GOLD).setLineWidth(1).rect(32, 32, W - 64, H - 64);

    // ---- Certificate ----
    let y = 82;
    doc.setTextColor.apply(doc, MUTED).setFont('helvetica', 'bold').setFontSize(10);
    doc.text('ACC 211 PRINCIPLES OF ACCOUNTING  |  MERCHANDISING OPERATIONS', cx, y, { align: 'center' });
    y += 40;
    doc.setTextColor.apply(doc, BRAND).setFont('times', 'bold').setFontSize(34);
    doc.text('Certificate of Completion', cx, y, { align: 'center' });
    y += 30;
    doc.setTextColor.apply(doc, INK).setFont('helvetica', 'normal').setFontSize(12);
    doc.text('This certifies that', cx, y, { align: 'center' });
    y += 38;
    doc.setFont('times', 'bolditalic').setFontSize(30);
    doc.text(t(state.name), cx, y, { align: 'center' });
    doc.setDrawColor.apply(doc, GOLD).setLineWidth(1).line(cx - 170, y + 10, cx + 170, y + 10);
    y += 34;
    doc.setFont('helvetica', 'normal').setFontSize(11.5);
    const body = 'has journalized and posted all 15 November transactions of Bright Mart under the perpetual inventory system, ' +
      'including purchases, freight, returns, allowances, discounts, sales and operating expenses, and generated the ' +
      'multi-step income statement below from the general ledger.';
    const lines = doc.splitTextToSize(body, W - 200);
    doc.text(lines, cx, y, { align: 'center', lineHeightFactor: 1.4 });
    y += lines.length * 16 + 14;

    const completed = new Date(state.completedAt).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
    doc.setFontSize(10).setTextColor.apply(doc, MUTED);
    doc.text(t('Completed ' + completed + '     |     Certificate ID ' + certId), cx, y, { align: 'center' });
    y += 30;

    // ---- Income statement ----
    doc.setTextColor.apply(doc, INK).setFont('helvetica', 'bold').setFontSize(12);
    doc.text(t(statement.business), cx, y, { align: 'center' });
    doc.text('Income Statement', cx, y + 15, { align: 'center' });
    doc.setFont('helvetica', 'normal').setFontSize(10.5);
    doc.text(t(statement.period), cx, y + 29, { align: 'center' });
    y += 38;

    const rows = window.GLStatementRows(statement);
    const fmt = function (v, i, r) {
      if (v === '') return '';
      const dollar = i === 0 || r[3] === 'final';
      return (dollar ? E.money(Math.abs(v)) : Math.abs(v).toLocaleString('en-US'));
    };
    const tableW = 400;
    doc.autoTable({
      startY: y, margin: { left: (W - tableW) / 2, right: (W - tableW) / 2 }, tableWidth: tableW, theme: 'plain',
      body: rows.map(function (r, i) { return [t(r[0]), fmt(r[1], i, r), fmt(r[2], i, r)]; }),
      styles: { fontSize: 10.5, cellPadding: { top: 2.5, bottom: 2.5, left: 4, right: 4 }, textColor: INK },
      columnStyles: { 1: { halign: 'right', cellWidth: 75 }, 2: { halign: 'right', cellWidth: 75 } },
      didParseCell: function (d) {
        const r = rows[d.row.index];
        if (d.column.index === 0 && (r[3] === 'in' || r[3] === 'in2')) d.cell.styles.cellPadding = { top: 2.5, bottom: 2.5, left: r[3] === 'in' ? 18 : 32, right: 4 };
        if (r[3] === 'key' || r[3] === 'final') d.cell.styles.fontStyle = 'bold';
        if (r[3] === 'key' && d.column.index === 0) d.cell.styles.textColor = BRAND;
      },
      didDrawCell: function (d) {
        const r = rows[d.row.index];
        if (d.column.index === 0 || d.cell.raw === '') return;
        const x1 = d.cell.x + 8, x2 = d.cell.x + d.cell.width - 2, yb = d.cell.y + d.cell.height - 1;
        doc.setDrawColor.apply(doc, INK).setLineWidth(0.7);
        if (r[4]) doc.line(x1, yb, x2, yb);
        if (r[3] === 'final') { doc.line(x1, yb, x2, yb); doc.line(x1, yb + 2.5, x2, yb + 2.5); }
      }
    });

    doc.setFontSize(8.5).setTextColor.apply(doc, MUTED).setFont('helvetica', 'normal');
    doc.text('Generated by the ACC 211 Bright Mart General Ledger practice set.', cx, H - 46, { align: 'center' });

    doc.save('ACC211_GL_Certificate_' + state.name.replace(/[^A-Za-z0-9]+/g, '_').replace(/^_|_$/g, '') + '.pdf');
  }

  window.GLReport = { download: download };
})();
