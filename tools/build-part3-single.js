// Builds a single self-contained HTML file of the Part 3 practice app from part3-site/.
// Every stylesheet and script (including the bundled PDF library) is inlined, so the file
// works on its own: double-click to open, email it, or put it on a shared drive.
// Run with: node tools/build-part3-single.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = path.join(root, 'part3-site');
const OUT = path.join(root, 'part3-single', 'ACC211_Merch_Statements.html');

function build() {
  let html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
  const read = rel => fs.readFileSync(path.join(src, rel), 'utf8');

  const css = (html.match(/<link rel="stylesheet" href=/g) || []).length;
  const js = (html.match(/<script src=/g) || []).length;
  let inlined = 0;
  html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (m, href) => { inlined++; return '<style>\n' + read(href) + '\n</style>'; });
  html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, file) => {
    // "</script" inside a script would end the tag early; escape it defensively.
    inlined++;
    const code = read(file).replace(/<\/script/gi, '<\\/script');
    return '<script>\n' + code + '\n</script>';
  });
  if (inlined !== css + js) throw new Error('An external file was not inlined.');

  return html.replace('<head>', '<head>\n  <!-- GENERATED by tools/build-part3-single.js from part3-site/. Edit files there, then rebuild. -->');
}

module.exports = { build, OUT };
if (require.main === module) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const html = build();
  fs.writeFileSync(OUT, html);
  console.log('Wrote ' + path.relative(root, OUT) + ' (' + Math.round(Buffer.byteLength(html) / 1024) + ' KB)');
}
