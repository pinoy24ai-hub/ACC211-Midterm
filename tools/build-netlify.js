// Builds netlify/<site>/index.html for each site in src/: one self-contained file with every
// stylesheet and script (including the bundled PDF library) written inline.
// Run with: node tools/build-netlify.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const SITES = ['midterm-exam', 'gl-practice', 'gl-workshop', 'cobblestone', 'cobblestone-quiz'];
const BANNER = '<!-- GENERATED by tools/build-netlify.js from src/SITE/. Edit files there, then rebuild. -->\n';

function build(site) {
  const dir = path.join(root, 'src', site);
  const read = (rel) => fs.readFileSync(path.join(dir, rel), 'utf8');
  let html = read('index.html');
  const assets = (html.match(/<link rel="stylesheet"|<script src=/g) || []).length;
  let inlined = 0;
  html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) => (inlined++, '<style>\n' + read(href) + '\n</style>'));
  // "</script" inside inlined code would end the tag early, so escape it.
  html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => (inlined++, '<script>\n' + read(src).replace(/<\/script/gi, '<\\/script') + '\n</script>'));
  if (inlined !== assets) throw new Error(site + ': an asset was not inlined');
  return html.replace(/^<!doctype html>\n/i, (m) => m + BANNER.replace('SITE', site));
}

function buildAll() {
  const out = {};
  SITES.forEach((site) => { out[site] = build(site); });
  return out;
}

module.exports = { SITES, build, buildAll };
if (require.main === module) {
  const all = buildAll();
  SITES.forEach((site) => {
    const outDir = path.join(root, 'netlify', site);
    fs.rmSync(outDir, { recursive: true, force: true });
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, 'index.html'), all[site]);
    console.log('Wrote netlify/' + site + '/index.html (' + Math.round(all[site].length / 1024) + ' KB)');
  });
}
